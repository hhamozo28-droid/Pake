    head("الملحق (ب) — ملاحظات المُعرِب والتصحيحات، بحسب مواضعها")
    notes = []
    for fn in sorted(glob.glob("work/fcar/*.md")):
        pg = None
        for line in open(fn, encoding="utf-8").read().split("\n"):
            m = re.match(r"^#PAGE\s+(\d+)", line)
            if m:
                pg = int(m.group(1)); continue
            if line.startswith("@NOTE"):
                notes.append((pg, line[5:].strip()))
    for i, (pg, t) in enumerate(notes, 1):
        P(f"{i}- [صفحة {pg}] {t}", size=12)
    P(f"عدد الملاحظات: {len(notes)} — وهي مُدرَجة أيضًا في محلّها من المتن (باللون الأحمر)، وهذا الملحق فهرسُها فقط.", size=11, color="C00000")

