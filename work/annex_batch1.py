def build(doc, blocks, LINEBY, FIGDIR, REG, P, add_table, add_picture, shade, rtl_paragraph,
          WD_ALIGN, Pt_, Cm_, RGB_, WD_BRK):
    from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
    def head(text, style='Heading 1'):
        h = doc.add_paragraph(style=style); rtl_paragraph(h); h.add_run(text)
        doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    rows = []
    for pg, sup, fr, ar in MANUAL:
        rows.append([str(pg), sup, fr, ar])
    extra_ids = set()
    for pg, sup, fr, ar in MANUAL:
        for tok in str(sup).replace("(", " ").replace(")", " ").replace("/", " ").replace(",", " ").split():
            if "_r" in tok or "_d" in tok:
                extra_ids.add(tok)
    for p in blocks["pages"]:
        if not (1 <= p["page"] <= 61):
            continue
        for r in p["regions"]:
            if r["id"] in extra_ids:
                continue
            if not r.get("has_image", True):
                continue
            if r["w_pt"] * r["h_pt"] > 0.70 * 595 * 841:
                continue
            lines = [l["text"].strip() for l in p["lines"] if l["reg"] == r["id"] and l["text"].strip()]
            if not lines:
                continue
            fr = " — ".join(lines)
            if len(fr) < 8:
                continue
            rows.append([str(p["page"]), f"{r['id']} ({r['kind']})", fr,
                         "تُرجمت في صلب الدليل (التسمية تحت الصورة / الجدول العربيّ المقابل)"])
    ex = f"work/{os.environ.get('TAG', 'batch1')}_extra.json"
    if os.path.exists(ex):
        for e in json.load(open(ex)):
            if e["id"] in extra_ids:
                continue
            rows.append([str(e["page"]), f"{e['id']} (صورة مستعادة)",
                         "لا نصّ: أيقونة/عنصر زخرفة صغير ملحق بإطار الصفحة",
                         "فُحصت على ورقة تلامس فتبيّن أنّها بلا محتوى؛ لم تُدرَج في المتن"])
    rows.sort(key=lambda r: (int(r[0]), str(r[1])))
    head("الملحق (أ) — النصوص الواردة داخل الصور ولوحات الأصل (الدفعة الأولى: ص1–61)")
    P("تضمّ هذه القائمة كلّ نصّ داخل صورة أو بطاقة مصوَّرة في صفحات الأصل 1–61: بطاقات الأقمشة ويافطاتها، بطاقات التمرين، "
      "جداول الحساب المصوَّرة، جرد التسمية ومقاطع الإخراج، صور خطوات الفرش والتقطيع، وأيقونات لا نصّ فيها (ذُكرت كذلك "
      "حتى لا تُتجاوَز بصمت). وما كان من تسمية شكل مدرجة في طبقة النصّ فقد تُرجم تحت الصورة نفسها في المتن، ويُشار إلى ذلك "
      "في العمود الأخير. والصور المنقولة بصيغة «صفحة كاملة» لا يمكن تصحيح نصّها من داخل الوورد؛ لأنّها صورة لصفحة الأصل.",
      size=12)
    add_table(rows, header="صفحة الأصل||الصورة / اللوحة||النصّ كما ورد في الأصل||الترجمة العربية والموضع", fontsz=9)

    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    head("الملحق (ب) — ملاحظات المترجم والتصحيحات والبنود التي تحتاج تأكيدًا (الدفعة الأولى)")
    for i, n in enumerate(NOTES, 1):
        P(f"{i}- {n}", size=13)

    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    head("الملحق (ج) — مسرد مصطلحات الدفعة الأولى (مواصفات التحضير، الأقمشة، الفرش والتقطيع)")
    P("يُضاف هذا المسرد إلى مَسارد الدفعات الأخرى؛ وهو مستمدّ من الفصل الأوّل (مواصفات تحضير ستر الرجل) وبطاقات "
      "الأقمشة والتمارين المرافقة له. وقد ثُبِّتت المصطلحات بتاريخ 4 نوفمبر 2026 فأصبحت نهائيّة.", size=12)
    P(CONFIRM, size=11, color="C00000")
    add_table([[fr, ar] for fr, ar in GLOSS_EXTRA], header="الفرنسية||العربية", fontsz=11)
